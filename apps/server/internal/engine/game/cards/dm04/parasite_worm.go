// GregorianWorm ...
func GregorianWorm(c *match.Card) {

	c.Name = "Gregorian Worm"
	c.Power = 3000
	c.Civs = []string{civ.Darkness}
	c.Family = []string{family.ParasiteWorm}
	c.ManaCost = 4
	c.ManaRequirement = []string{civ.Darkness}

	c.Use(fx.Creature, fx.ShieldTrigger)

}
